fruits = ["apple", "banana", "orange", "grape"]

print("=== Full list ===")
print(fruits)

print("=== First item ===")
print(fruits[0])

print("=== Second item ===")
print(fruits[1])

print("=== Third item ===")
print(fruits[2])

print("=== Fourth item ===")
print(fruits[3])

print("=== Loop through list ===")
for fruit in fruits:
    print(fruit)

print("=== Length of list ===")
print(len(fruits))